CREATE TABLE IF NOT EXISTS gym_staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id VARCHAR(50) NOT NULL UNIQUE,
    user_id BIGINT REFERENCES fit_users(id),
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(255),
    designation VARCHAR(255) NOT NULL,
    specialization VARCHAR(255),
    experience_years INTEGER DEFAULT 1,
    qualifications TEXT,
    employment_type VARCHAR(50) NOT NULL DEFAULT 'FULL_TIME',
    joining_date DATE NOT NULL,
    resignation_date DATE,
    monthly_salary DOUBLE PRECISION,
    employment_status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    shift_schedule VARCHAR(255),
    profile_image_url VARCHAR(255),
    bio TEXT,
    emergency_contact VARCHAR(255),
    application_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS job_vacancies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    department VARCHAR(255),
    specialization VARCHAR(255),
    vacancies_count INTEGER NOT NULL DEFAULT 1,
    filled_count INTEGER NOT NULL DEFAULT 0,
    job_description TEXT NOT NULL,
    required_qualifications TEXT,
    min_experience INTEGER DEFAULT 1,
    preferred_experience INTEGER,
    employment_type VARCHAR(50) NOT NULL DEFAULT 'FULL_TIME',
    salary_range VARCHAR(255),
    is_salary_published BOOLEAN DEFAULT FALSE,
    location VARCHAR(255),
    opening_date DATE NOT NULL,
    deadline_date DATE NOT NULL,
    expected_joining_date DATE,
    working_days_shift VARCHAR(255),
    status VARCHAR(50) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS trainer_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number VARCHAR(50) NOT NULL UNIQUE,
    vacancy_id BIGINT NOT NULL REFERENCES job_vacancies(id) ON DELETE CASCADE,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    current_location VARCHAR(255),
    desired_position VARCHAR(255),
    experience_years INTEGER DEFAULT 0,
    specialization VARCHAR(255),
    educational_qualifications VARCHAR(255),
    fitness_certifications VARCHAR(255),
    previous_experience TEXT,
    professional_summary TEXT,
    availability_date DATE,
    resume_file_name VARCHAR(255),
    resume_file_path VARCHAR(255),
    portfolio_url VARCHAR(255),
    consent_given BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(50) NOT NULL DEFAULT 'SUBMITTED',
    internal_notes TEXT,
    interview_date DATE,
    interview_time VARCHAR(50),
    interview_location VARCHAR(255),
    interview_notes TEXT,
    converted_to_staff BOOLEAN DEFAULT FALSE,
    converted_staff_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS application_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES trainer_applications(id) ON DELETE CASCADE,
    from_status VARCHAR(50),
    to_status VARCHAR(50) NOT NULL,
    changed_by VARCHAR(255),
    reason_or_notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS staff_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id BIGINT NOT NULL REFERENCES gym_staff(id) ON DELETE CASCADE,
    shift_name VARCHAR(255) NOT NULL,
    day_of_week VARCHAR(50),
    specific_date DATE,
    start_time VARCHAR(50) NOT NULL,
    end_time VARCHAR(50) NOT NULL,
    is_recurring BOOLEAN DEFAULT TRUE,
    is_rest_day BOOLEAN DEFAULT FALSE,
    notes VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_staff_email ON gym_staff(email);
CREATE INDEX IF NOT EXISTS idx_vacancies_status ON job_vacancies(status);
CREATE INDEX IF NOT EXISTS idx_applications_vacancy ON trainer_applications(vacancy_id);
CREATE INDEX IF NOT EXISTS idx_applications_status ON trainer_applications(status);
CREATE INDEX IF NOT EXISTS idx_schedules_staff ON staff_schedules(staff_id);
